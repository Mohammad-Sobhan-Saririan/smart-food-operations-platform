import sqlite3 from 'sqlite3';
import { open } from 'sqlite';
import { nanoid } from 'nanoid';
import path from 'path';
import fs from 'fs';
import { env } from '../config/env.js';

// This is a top-level async function that we'll call to initialize the DB
async function setup() {
  if (env.dbPath !== ':memory:') {
    const dir = path.dirname(path.resolve(env.dbPath));
    fs.mkdirSync(dir, { recursive: true });
  }
  const db = await open({
    filename: env.dbPath,
    driver: sqlite3.Database
  });

  await db.exec('PRAGMA foreign_keys = ON');

  // Core cafe and restaurant schema
  await db.exec(`
    CREATE TABLE IF NOT EXISTS products (
      id TEXT PRIMARY KEY,
      name TEXT NOT NULL,
      price INTEGER NOT NULL,
      category TEXT NOT NULL,
      imageUrl TEXT,
      rating REAL DEFAULT 0,
      maxOrderPerUser INTEGER DEFAULT 5,
      description TEXT,
      stock INTEGER DEFAULT 100,
      isDisabled BOOLEAN DEFAULT 0
    )
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS floors (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      name TEXT NOT NULL UNIQUE
    )
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS orders (
      id TEXT PRIMARY KEY,
      userId TEXT,
      items TEXT NOT NULL,
      totalAmount INTEGER NOT NULL,
      status TEXT DEFAULT 'Pending',
      description TEXT,
      priority INTEGER DEFAULT 1, -- 1 = Normal, 2 = High
      createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
      deliveryFloorId INTEGER REFERENCES floors(id),
      clientRequestId TEXT, -- NEW: idempotency key generated by client
      FOREIGN KEY (userId) REFERENCES users (id)
    );
  `);

  // 2. Modify the orders table
  await db.exec(`
    CREATE TABLE IF NOT EXISTS configs (
      feature TEXT PRIMARY KEY,
      isEnabled BOOLEAN NOT NULL,
      value TEXT
    )
  `);

  await db.exec(`
  CREATE TABLE IF NOT EXISTS reports (
    id TEXT PRIMARY KEY,
    adminId TEXT NOT NULL,
    name TEXT NOT NULL,
    nl_query TEXT,
    sql_query TEXT NOT NULL,
    viz_type TEXT DEFAULT 'table',
    -- ADD THE FOLLOWING TWO COLUMNS --
    chart_config TEXT, -- Will store the chart settings as a JSON string
    conversation_history TEXT, -- Will store the chat history as a JSON string
    createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (adminId) REFERENCES users (id));
  `);

  // FCM Tokens table
  await db.exec(`
    CREATE TABLE IF NOT EXISTS fcm_tokens (
    token TEXT PRIMARY KEY,
    userId TEXT NOT NULL,
    platform TEXT,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP);
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_roles (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL UNIQUE,
    DisplayName TEXT NOT NULL);
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_permissions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL UNIQUE,
    description TEXT);
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_role_permissions (
    roleId INTEGER NOT NULL,
    permissionId INTEGER NOT NULL,
    PRIMARY KEY (roleId, permissionId),
    FOREIGN KEY (roleId) REFERENCES rst_roles(id) ON DELETE CASCADE,
    FOREIGN KEY (permissionId) REFERENCES rst_permissions(id) ON DELETE CASCADE);
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_meal_types (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL UNIQUE,
    DisplayName TEXT NOT NULL);
  `);


  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_dishes (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL UNIQUE,
    companyId INTEGER REFERENCES rst_companies(id),
    description TEXT,
    imageUrl TEXT);
  `);


  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_entitlement_groups (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL UNIQUE,
    DisplayName TEXT NOT NULL);
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_daily_entitlements (
    groupId INTEGER NOT NULL,
    dayOfWeek INTEGER NOT NULL,
    mealTypeId INTEGER NOT NULL,
    dishCount INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (groupId, dayOfWeek, mealTypeId),
    FOREIGN KEY (groupId) REFERENCES rst_entitlement_groups(id),
    FOREIGN KEY (mealTypeId) REFERENCES rst_meal_types(id));
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_menus (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      weekStartDate TEXT NOT NULL,
      companyId INTEGER REFERENCES rst_companies(id),
      UNIQUE (weekStartDate, companyId)
    );
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_daily_options (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      menuId INTEGER NOT NULL,
      dayOfWeek INTEGER NOT NULL,
      mealTypeId INTEGER NOT NULL,
      dishId INTEGER NOT NULL,
      isActive BOOLEAN DEFAULT 1,
      FOREIGN KEY (menuId) REFERENCES rst_menus(id),
      FOREIGN KEY (mealTypeId) REFERENCES rst_meal_types(id),
      FOREIGN KEY (dishId) REFERENCES rst_dishes(id));
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_reservations (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      userId TEXT NOT NULL,
      date TEXT NOT NULL,
      mealTypeId INTEGER NOT NULL,
      statusId INTEGER, -- This replaces the old 'status' TEXT column
      chosenDishIds TEXT,
      proxyUserId TEXT,
      savedWithPriority INTEGER DEFAULT 0,
      companyId INTEGER REFERENCES rst_companies(id),
      UNIQUE (userId, date, mealTypeId),
      FOREIGN KEY (userId) REFERENCES users(id),
      FOREIGN KEY (mealTypeId) REFERENCES rst_meal_types(id),
      FOREIGN KEY (statusId) REFERENCES rst_reservation_statuses(id)
    )
  `);


  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_reservation_statuses (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    title TEXT NOT NULL UNIQUE,
    nameFA TEXT NOT NULL UNIQUE,
    description TEXT,
    color TEXT DEFAULT '#FFFFFF' -- e.g., a hex color code
  );
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_entitlement_history (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        userId TEXT NOT NULL,
        entitlementGroupId INTEGER NOT NULL,
        changeType TEXT NOT NULL, -- e.g., 'added', 'removed'
        timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (userId) REFERENCES users(id),
        FOREIGN KEY (entitlementGroupId) REFERENCES rst_entitlement_groups(id)
    );
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_companies (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL UNIQUE
    );
  `);

  // the users table
  await db.exec(`
  CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    phone TEXT,
    country TEXT,
    city TEXT,
    age INTEGER,
    position TEXT,
    creditLimit INTEGER DEFAULT 1000000,
    creditBalance INTEGER DEFAULT 1000000,
    role TEXT NOT NULL DEFAULT 'user',
    employeeNumber TEXT UNIQUE,
    defaultFloorId INTEGER REFERENCES floors(id),
    defaultCompanyId INTEGER REFERENCES rst_companies(id),
    isAdUser BOOLEAN DEFAULT 0, -- Indicates if the user is an Active Directory user
    adAttributes TEXT, -- Stores additional AD attributes as a JSON string
    entitlementGroupId INTEGER,
    rst_roleId INTEGER,
    FOREIGN KEY (rst_roleId) REFERENCES rst_roles(id),
    FOREIGN KEY (entitlementGroupId) REFERENCES rst_entitlement_groups(id)
    )
`);

  await db.exec(`
  CREATE TABLE IF NOT EXISTS rst_delivery_locks (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    token TEXT UNIQUE NOT NULL,
    userId TEXT NOT NULL,
    filters TEXT NOT NULL,
    expiresAt DATETIME NOT NULL,
    createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
    deletedAt DATETIME,
    isRevoked BOOLEAN DEFAULT 0,
    FOREIGN KEY (userId) REFERENCES users(id)
  );
`);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS rst_delegations (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      ownerId TEXT NOT NULL,       -- مدیر (صاحب رزرو)
      delegateId TEXT NOT NULL,    -- جانشین
      priority INTEGER DEFAULT 1,  -- اولویت (1 بالاترین، 2، 3 و ...)
      startDate TEXT,              -- تاریخ شروع (شمسی یا میلادی - توافق بر شمسی)
      endDate TEXT,                -- تاریخ پایان
      createdAt DATETIME DEFAULT CURRENT_TIMESTAMP,
      FOREIGN KEY (ownerId) REFERENCES users(id),
      FOREIGN KEY (delegateId) REFERENCES users(id),
      UNIQUE(ownerId, delegateId)
    );
  `);





  await db.exec(`
    INSERT OR IGNORE INTO rst_roles (id, name, DisplayName) VALUES
    (1, 'Restaurant Admin', 'ادمین رستوران'),
    (2, 'Restaurant Manager', 'مدیر رستوران'),
    (3, 'Restaurant Staff', 'کارمند رستوران'),
    (4, 'Employee', 'کارمند')
  `);

  await db.exec(`
    INSERT OR IGNORE INTO rst_permissions (id, name, description) VALUES
    (1, 'restaurant:admin', 'Full access to all restaurant features'),
    (2, 'restaurant:manage_menu', 'Create, update, and delete menu items'),
    (3, 'restaurant:view_reports', 'View restaurant reports'),
    (4, 'restaurant:manage_entitlements', 'Manage employee meal entitlements'),
    (5, 'restaurant:staff', 'Check employee meal entitlements and reservations'),
    (6, 'restaurant:employee', 'Make and manage meal reservations'),
    (7, 'restaurant:check_lunch', 'Verify lunch receipt by employees')
  `);

  await db.exec(`
    INSERT OR IGNORE INTO rst_role_permissions (roleId, permissionId) VALUES
    (1, 1), -- Admin has all permissions
    (2, 2), -- Manager can manage menu
    (2, 3), -- Manager can view reports
    (2, 4), -- Manager can manage entitlements
    (3, 5), -- Staff can check entitlements and reservations
    (3, 7), -- Staff can check lunch receipts
    (4, 6)  -- Employee can make reservations
  `);

  await db.exec(`
    INSERT OR IGNORE INTO rst_meal_types (id, name, DisplayName) VALUES
    (1, 'Breakfast', 'صبحانه'),
    (2, 'Lunch', 'ناهار'),
    (3, 'Dinner', 'شام')
  `);

  await db.exec(`
    INSERT OR IGNORE INTO rst_entitlement_groups (id, name, DisplayName) VALUES
      (1, 'Employees', 'کارمندان'),
      (2, 'Managers', 'مدیران'),
      (3, 'Guests', 'مهمانان'),
      (4, 'Support', 'پشتیبانی')
  `);

  await db.exec(`
    INSERT OR IGNORE INTO rst_reservation_statuses (id, title, nameFA, description, color) VALUES
    (1, 'Reserved', 'رزرو شده توسط کاربر', 'The reservation has been made by the user.', '#FFA500'), -- Orange
    (2, 'Confirmed', 'تایید شده توسط مدیر', 'The reservation has been confirmed by the restaurant.', '#008080'), -- Cyan
    (3, 'Cancelled', 'لغو شده توسط کاربر', 'The reservation has been cancelled by the user.', '#FF0000'), -- Red
    (4, 'No Show', 'عدم حضور کارمند', 'The employee did not show up for the reservation.', '#0000FF'), -- Blue
    (5, 'Completed', 'تحویل کاربر شد', 'The reservation has been fulfilled.', '#008000') -- Green
    `);

  // Create a UNIQUE index so duplicate clientRequestId cannot be inserted
  await db.exec(`
  CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_clientRequestId ON orders(clientRequestId);
`);


  await db.exec(
    `INSERT OR IGNORE INTO configs(feature, isEnabled) VALUES('creditSystem', 0)`
  );

  await db.exec(
    `INSERT OR IGNORE INTO configs (feature, isEnabled, value) VALUES ('reservation_cutoff_hours', 1, '48')`
  );

  return { db, nanoid };
}

// Call the setup function and export the promise it returns
const dbPromise = setup();

export { dbPromise };